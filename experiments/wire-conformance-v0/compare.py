#!/usr/bin/env python3
"""Compare all implementation observations and render result tables.

Reads results/*.jsonl, writes results/MATRIX.md and results/ESCAPES.md.
Exits non-zero unless the conformance set (rust-reference, python-strict,
go-strict) passes every vector and agrees byte-for-byte on every escape
probe. Default/tuned profiles are observations and never fail the run.
This source is ASCII-only.
"""

import collections
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).parent
RESULTS = HERE / "results"
CONFORMANCE = ["rust-reference", "python-strict", "go-strict"]
ORDER = [
    "rust-reference", "python-strict", "go-strict",
    "python-default", "python-compact", "go-default", "go-v2-default", "go-tuned",
]


def render(data):
    out = []
    for b in data:
        if 0x21 <= b <= 0x7E and b != 0x60 and b != 0x7C:
            out.append(chr(b))
        else:
            out.append("<%02x>" % b)
    return "".join(out)


def diff_region(expected, got):
    p = 0
    while p < min(len(expected), len(got)) and expected[p] == got[p]:
        p += 1
    s = 0
    while (s < min(len(expected), len(got)) - p
           and expected[len(expected) - 1 - s] == got[len(got) - 1 - s]):
        s += 1
    lo = max(0, p - 12)
    return (render(expected[lo:len(expected) - s]), render(got[lo:len(got) - s]))


def main():
    corpus = json.loads((HERE / "vectors" / "envelope-v0.json").read_text())
    vectors = corpus["vectors"]
    wire = {v["id"]: bytes.fromhex(v["wire_hex"]) for v in vectors}

    rows = {}
    escapes = collections.defaultdict(dict)
    probes = []
    for path in sorted(RESULTS.glob("*.jsonl")):
        for line in path.read_text().splitlines():
            r = json.loads(line)
            if r["type"] == "vector":
                rows[(r["impl"], r["vector"])] = r
            elif r["type"] == "escape":
                escapes[r["codepoint"]][r["impl"]] = r
            elif r["type"] == "probe":
                probes.append(r)

    impls = [i for i in ORDER if any(k[0] == i for k in rows)]
    missing = [i for i in CONFORMANCE if i not in impls]
    failures = [f"missing results for {i}" for i in missing]

    def cell(r):
        if r["pass"]:
            return "ok"
        if r["class"] == "negative":
            return "ACCEPTED"
        codes = []
        if r["encode"] == "mismatch":
            codes.append("ENC!=")
        elif r["encode"] == "error":
            codes.append("ENC-ERR")
        if r["decode"] == "reject":
            codes.append("REJECTED")
        elif r["fields_match"] is False:
            codes.append("FIELDS!=")
        return " ".join(codes)

    lines = ["# Envelope V0 wire conformance matrix", "",
             "Generated by `compare.py` from `results/*.jsonl`. Do not edit.", "",
             "Conformance set: " + ", ".join(f"`{i}`" for i in CONFORMANCE)
             + ". Other columns are observations of ordinary library behaviour.", "",
             "Cell codes: `ok` pass; `ENC!=` encoder output differs from expected bytes; "
             "`REJECTED` canonical positive rejected; `FIELDS!=` decoded fields differ; "
             "`ACCEPTED` negative vector accepted.", "",
             "## Summary", "", "| implementation | positives | negatives | total |",
             "|---|---|---|---|"]
    npos = sum(v["class"] == "positive" for v in vectors)
    nneg = len(vectors) - npos
    for i in impls:
        pp = sum(rows[(i, v["id"])]["pass"] for v in vectors if v["class"] == "positive")
        nn = sum(rows[(i, v["id"])]["pass"] for v in vectors if v["class"] == "negative")
        lines.append(f"| `{i}` | {pp}/{npos} | {nn}/{nneg} | {pp + nn}/{len(vectors)} |")
    lines += ["", "## Per vector", "",
              "| vector | " + " | ".join(f"`{i}`" for i in impls) + " |",
              "|---" * (len(impls) + 1) + "|"]
    for v in vectors:
        cells = [cell(rows[(i, v["id"])]) for i in impls]
        lines.append(f"| `{v['id']}` | " + " | ".join(cells) + " |")

    lines += ["", "## Encoder divergences (positives)", "",
              "Expected vs produced bytes around the first difference "
              "(`<xx>` = byte outside printable ASCII).", "",
              "| implementation | vector | expected | produced |", "|---|---|---|---|"]
    for i in impls:
        for v in vectors:
            r = rows[(i, v["id"])]
            if r["encode"] == "mismatch":
                e, g = diff_region(wire[v["id"]], bytes.fromhex(r["encoded_hex"]))
                lines.append(f"| `{i}` | `{v['id']}` | `{e}` | `{g}` |")

    lines += ["", "## Accepted negatives (decoder divergences)", "",
              "| implementation | accepted negative vectors |", "|---|---|"]
    for i in impls:
        acc = [v["id"] for v in vectors
               if v["class"] == "negative" and rows[(i, v["id"])]["decode"] == "accept"]
        lines.append(f"| `{i}` | {', '.join(f'`{a}`' for a in acc) or '-'} |")

    rejected_pos = [(i, v["id"], rows[(i, v["id"])]["detail"]) for i in impls for v in vectors
                    if v["class"] == "positive" and rows[(i, v["id"])]["decode"] == "reject"]
    if rejected_pos:
        lines += ["", "## Canonical positives rejected", "",
                  "| implementation | vector | reason |", "|---|---|---|"]
        lines += [f"| `{i}` | `{vid}` | {d} |" for i, vid, d in rejected_pos]

    if probes:
        lines += ["", "## Supplementary probes", "", "| implementation | probe | output |",
                  "|---|---|---|"]
        for p in probes:
            lines.append(f"| `{p['impl']}` | {p['probe']} | `{p['output']}` |")

    (RESULTS / "MATRIX.md").write_text("\n".join(lines) + "\n")

    # Escape table.
    ref = "rust-reference"
    elines = ["# String escape observations", "",
              "Generated by `compare.py`. Body literal emitted for a one-character body. "
              "`<xx>` = byte outside printable ASCII. `*` marks divergence from "
              f"`{ref}`.", "",
              "| code point | " + " | ".join(f"`{i}`" for i in impls) + " |",
              "|---" * (len(impls) + 1) + "|"]
    for cp in corpus["escape_probe_codepoints"]:
        per = escapes[cp]
        base = per.get(ref, {}).get("literal_hex")
        cells = []
        for i in impls:
            r = per.get(i)
            if r is None:
                cells.append("-")
            elif r["literal_hex"] is None:
                cells.append("error")
            else:
                mark = "" if r["literal_hex"] == base else " *"
                cells.append(f"`{render(bytes.fromhex(r['literal_hex']))}`{mark}")
        elines.append(f"| U+{cp:04X} | " + " | ".join(cells) + " |")
        literals = {per[i]["literal_hex"] for i in CONFORMANCE if i in per}
        if len(literals) != 1:
            failures.append(f"escape disagreement at U+{cp:04X}")
    (RESULTS / "ESCAPES.md").write_text("\n".join(elines) + "\n")

    for i in CONFORMANCE:
        for v in vectors:
            r = rows.get((i, v["id"]))
            if r is None or not r["pass"]:
                failures.append(f"{i} fails {v['id']}")
    for v in vectors:
        decisions = {rows[(i, v["id"])]["decode"] for i in CONFORMANCE if (i, v["id"]) in rows}
        if len(decisions) > 1:
            failures.append(f"conformance decode disagreement on {v['id']}")

    for i in impls:
        passed = sum(rows[(i, v["id"])]["pass"] for v in vectors)
        print(f"{i:16} {passed}/{len(vectors)}")
    if failures:
        print("CONFORMANCE FAILURE:")
        for f in failures:
            print("  " + f)
        return 1
    print("CONFORMANCE: rust-reference, python-strict, go-strict agree on all vectors and escapes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
